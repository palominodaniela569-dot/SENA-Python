#Pide al usuario un número.

#Si es mayor que 100, muestra Es mayor que 100
#Si es menor que 100, muestra Es menor que 100
#Si es igual a 100, muestra Es exactamente 100

numero = int(input("Ingrese un numero: "))

if numero >100:
    print("Es mayor que 100")

elif numero <100:
    print("Tu numero es menor que 100")

else:
    print("es exactamente 100")
