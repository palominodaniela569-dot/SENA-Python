developer = 'Devin'

#Para ver qué tipo es developer, puedes usar la función type() así:

print(type(developer)) # <class 'str'>

#La salida de <class 'str'> significa que developer es un tipo cadena.

#Aquí están los tipos de datos que has aprendido hasta ahora, junto con
# lo que la función type() imprime para cada uno:

my_integer_var = 10
print(type(my_integer_var))  # <class 'int'>

my_float_var = 4.50
print(type(my_float_var))  # <class 'float'>

my_string_var = 'hello'
print(type(my_string_var))  # <class 'str'>

my_boolean_var = True
print(type(my_boolean_var))  # <class 'bool'>